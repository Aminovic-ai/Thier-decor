-- REVIEW ONLY. Do not run on production until the live schema and prerequisite RPC helpers are verified.
-- Intended to run only after td_build_order_items(jsonb) and td_order_stock_requirements(jsonb)
-- are present and the Worker action is ready.

begin;

create table if not exists public.td_store_sales (
  id bigint generated by default as identity primary key,
  request_key uuid not null unique,
  invoice_no text unique,
  items jsonb not null,
  items_total numeric(12,2) not null,
  discount numeric(12,2) not null default 0,
  total numeric(12,2) not null,
  payment_method text not null,
  paid_amount numeric(12,2) not null,
  created_at timestamptz not null default now(),
  cashier_uid text
);

alter table public.td_store_sales enable row level security;
revoke all on public.td_store_sales from public, anon, authenticated;
grant select, insert, update, delete on public.td_store_sales to service_role;
grant usage, select on sequence public.td_store_sales_id_seq to service_role;

create or replace function public.td_admin_create_store_sale(p_sale jsonb)
returns jsonb
language plpgsql
security definer
set search_path=public,pg_temp
as $$
declare
  v_request_key uuid;
  canonical_items jsonb;
  required jsonb;
  item_key text;
  required_qty numeric;
  stock_qty integer;
  subtotal numeric(12,2) := 0;
  discount_amount numeric(12,2) := 0;
  total_amount numeric(12,2);
  paid numeric(12,2);
  payment text;
  cashier text;
  sale_id bigint;
  invoice text;
  existing_sale public.td_store_sales%rowtype;
begin
  if jsonb_typeof(p_sale) <> 'object' then
    raise exception 'Sale payload must be a JSON object';
  end if;

  begin
    v_request_key := (p_sale->>'request_key')::uuid;
  exception when others then
    raise exception 'A valid request key is required';
  end;

  perform pg_advisory_xact_lock(hashtext('td-store-sale:' || v_request_key::text));
  select * into existing_sale
    from public.td_store_sales
    where td_store_sales.request_key = v_request_key
    for update;
  if found then
    return jsonb_build_object(
      'ok', true,
      'sale_id', existing_sale.id,
      'invoice_no', existing_sale.invoice_no,
      'total', existing_sale.total,
      'already_created', true
    );
  end if;

  canonical_items := public.td_build_order_items(p_sale->'items');
  required := public.td_order_stock_requirements(canonical_items);

  for item_key, required_qty in
    select key, value::numeric from jsonb_each_text(required) order by key::bigint
  loop
    select qty into stock_qty
      from public.products
      where id = item_key::bigint
      for update;
    if not found then
      raise exception 'Required stock product % does not exist', item_key;
    end if;
    if stock_qty < required_qty then
      raise exception 'Insufficient stock for product % (required %, available %)',
        item_key, required_qty, stock_qty;
    end if;
  end loop;

  select coalesce(sum((item->>'price')::numeric * (item->>'qty')::numeric), 0)
    into subtotal
    from jsonb_array_elements(canonical_items) as lines(item);

  discount_amount := coalesce((p_sale->>'discount')::numeric, 0);
  if discount_amount < 0 or discount_amount > subtotal then
    raise exception 'Invalid sale discount';
  end if;
  total_amount := round(subtotal - discount_amount, 2);

  payment := lower(trim(coalesce(p_sale->>'payment_method', 'cash')));
  if payment not in ('cash','transfer','card','other') then
    raise exception 'Invalid payment method';
  end if;
  paid := coalesce((p_sale->>'paid_amount')::numeric, total_amount);
  if paid < 0 or paid > total_amount then
    raise exception 'Invalid paid amount';
  end if;
  cashier := left(trim(coalesce(p_sale->>'cashier_uid','')), 128);

  insert into public.td_store_sales (
    request_key, items, items_total, discount, total,
    payment_method, paid_amount, cashier_uid
  ) values (
    v_request_key, canonical_items, subtotal, discount_amount, total_amount,
    payment, paid, nullif(cashier,'')
  ) returning id into sale_id;

  invoice := 'TD-' || to_char(now(), 'YYYYMMDD') || '-' || lpad(sale_id::text, 6, '0');
  update public.td_store_sales set invoice_no = invoice where id = sale_id;

  for item_key, required_qty in
    select key, value::numeric from jsonb_each_text(required) order by key::bigint
  loop
    update public.products
      set qty = qty - required_qty::integer
      where id = item_key::bigint;
  end loop;

  return jsonb_build_object(
    'ok', true,
    'sale_id', sale_id,
    'invoice_no', invoice,
    'items_total', subtotal,
    'discount', discount_amount,
    'total', total_amount,
    'paid_amount', paid,
    'items', canonical_items,
    'already_created', false
  );
end;
$$;

revoke all on function public.td_admin_create_store_sale(jsonb) from public, anon, authenticated;
grant execute on function public.td_admin_create_store_sale(jsonb) to service_role;

commit;
