-- E. Guarantee one promo-use row per order.
-- Existing duplicates cause a clear error and rollback; no rows are deleted.
-- This constraint is safe with the current text order_id representation.
-- ---------------------------------------------------------------------------
DO $$
DECLARE
  v_constraint_exists boolean;
  v_duplicates bigint;
BEGIN
  SELECT EXISTS (
    SELECT 1
    FROM pg_constraint c
    JOIN pg_class t ON t.oid=c.conrelid
    JOIN pg_namespace n ON n.oid=t.relnamespace
    WHERE n.nspname='public'
      AND t.relname='td_promo_uses'
      AND c.contype='u'
      AND pg_get_constraintdef(c.oid) ILIKE '%(order_id)%'
  ) INTO v_constraint_exists;

  IF NOT v_constraint_exists THEN
    SELECT count(*) INTO v_duplicates
    FROM (
      SELECT order_id
      FROM public.td_promo_uses
      GROUP BY order_id
      HAVING count(*) > 1
    ) d;

    IF v_duplicates > 0 THEN
      RAISE EXCEPTION
        'Cannot add UNIQUE(order_id): % duplicated order_id groups exist in td_promo_uses. Review them manually; no rows were removed.',
        v_duplicates;
    END IF;

    ALTER TABLE public.td_promo_uses
      ADD CONSTRAINT td_promo_uses_order_id_unique UNIQUE (order_id);
  END IF;
END
$$;

