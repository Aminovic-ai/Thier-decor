-- Durable payment ledger for customer-credit orders.
-- This migration is additive: it preserves orders.paidAmount as the cached cumulative total.
create table if not exists public.td_order_payments (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  amount numeric(12,2) not null check (amount > 0),
  source text not null default 'admin',
  created_at timestamptz not null default now()
);

create index if not exists td_order_payments_order_created_idx
  on public.td_order_payments (order_id, created_at desc);

alter table public.td_order_payments enable row level security;
revoke all on table public.td_order_payments from anon, authenticated;
grant select, insert, update, delete on table public.td_order_payments to service_role;
grant usage, select on sequence public.td_order_payments_id_seq to service_role;

-- Preserve existing recorded cumulative payments as one legacy opening entry.
insert into public.td_order_payments (order_id, amount, source)
select id, "paidAmount", 'legacy_balance'
from public.orders
where coalesce("paidAmount", 0) > 0
  and not exists (
    select 1 from public.td_order_payments p
    where p.order_id = orders.id
  );

create or replace function public.td_record_order_payment(
  p_order_id bigint,
  p_amount numeric
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order public.orders%rowtype;
  v_paid numeric(12,2);
  v_remaining numeric(12,2);
  v_payment_id bigint;
begin
  if p_order_id is null or p_amount is null or p_amount <= 0 then
    raise exception 'مبلغ الدفعة غير صالح';
  end if;

  select * into v_order
  from public.orders
  where id = p_order_id
  for update;

  if not found then
    raise exception 'الطلبية غير موجودة';
  end if;
  if v_order.status = 'cancelled' then
    raise exception 'لا يمكن تسجيل دفعة لطلبية ملغاة';
  end if;

  v_paid := coalesce(v_order."paidAmount", 0);
  v_remaining := greatest(0, coalesce(v_order.total, 0) - v_paid);
  if p_amount > v_remaining then
    raise exception 'مبلغ الدفعة أكبر من الدين المتبقي';
  end if;

  insert into public.td_order_payments(order_id, amount, source)
  values (p_order_id, round(p_amount, 2), 'admin')
  returning id into v_payment_id;

  v_paid := v_paid + round(p_amount, 2);
  update public.orders
  set "paidAmount" = v_paid
  where id = p_order_id;

  return jsonb_build_object(
    'success', true,
    'paymentId', v_payment_id,
    'paidAmount', v_paid,
    'remainingDebt', greatest(0, coalesce(v_order.total, 0) - v_paid)
  );
end;
$$;

revoke all on function public.td_record_order_payment(bigint, numeric) from public, anon, authenticated;
grant execute on function public.td_record_order_payment(bigint, numeric) to service_role;
